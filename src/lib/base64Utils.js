/**
 * Base64 utility functions for UTF-8 encoding/decoding
 * Dùng để mã hóa/giải mã tiếng Việt khi lưu vào database Oracle
 */

/**
 * Encode UTF-8 string to Base64
 * @param str - String to encode
 * @returns Base64 encoded string
 */
export const encodeBase64UTF8 = (str) => {
    if (!str) return '';
    
    try {
        return btoa(unescape(encodeURIComponent(str)));
    } catch {
        // If encoding fails, return the original string
        return str;
    }
};

/**
 * Decode Base64 to UTF-8 string
 * @param str - Base64 string to decode
 * @returns Decoded UTF-8 string
 */
export const decodeBase64UTF8 = (str) => {
    if (!str) return '';
    
    try {
        return decodeURIComponent(escape(atob(str)));
    } catch {
        // If decoding fails, return the original string
        return str;
    }
};

